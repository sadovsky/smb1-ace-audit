"""Generate and check every obligation; write the manifest and status report.

    python3 -m formal.run

Requires the verified image (`SMB1_ROM`).  Nothing here is cached: every
status in the manifest comes from a query run in this invocation.
"""
from __future__ import annotations

import json
import os
import platform
import subprocess
import time

import z3

from .properties import (bounded, dispatch, graph_check, init_memory,
                         instruction_location, stack_separation,
                         state_domains)
from .properties.common import context
from .verify.obligations import STATUSES, Ledger

HERE = os.path.dirname(os.path.abspath(__file__))
MANIFEST = os.path.join(HERE, "results", "manifests", "obligations.json")
REPORT = os.path.join(HERE, "results", "reports", "status.md")
VALIDATION = os.path.join(HERE, "results", "reports", "model_validation.json")


def _commit() -> str:
    try:
        return subprocess.run(["git", "rev-parse", "HEAD"], cwd=HERE,
                              capture_output=True, text=True,
                              check=True).stdout.strip()
    except Exception:
        return "unknown"


def _validation_summary() -> dict:
    if not os.path.exists(VALIDATION):
        return {"status": "not run"}
    with open(VALIDATION) as handle:
        report = json.load(handle)
    return {key: {k: report[key].get(k) for k in
                  ("source", "instructions_compared", "mismatch_count",
                   "status", "reason") if k in report[key]}
            for key in ("vectors", "py65")}


def build() -> tuple[Ledger, dict]:
    ctx = context()
    ledger = Ledger()
    timings = {}
    modules = [graph_check, dispatch, state_domains, init_memory,
               stack_separation, bounded]
    if os.environ.get("SMB1_JOINT") == "1":
        # The certificate route is opt-in: the checker has known soundness
        # gaps (formal/lean/FINDINGS.md) and its verdicts must not enter the
        # manifest by default until they are closed.
        from .properties import joint
        modules.append(joint)
    modules.append(instruction_location)
    for module in modules:
        started = time.time()
        module.run(ledger, ctx)
        timings[module.__name__.rsplit(".", 1)[-1]] = round(
            time.time() - started, 1)
    ledger.settle()
    try:
        import cvc5
        second = cvc5.__version__
    except Exception:
        second = None
    header = {
        "rom_sha1": ctx.sha1,
        "repository_commit": _commit(),
        "machine_model": "formal/model (instruction-level 2A03, NROM-256)",
        "model_validation": _validation_summary(),
        "solver": {"z3": z3.get_version_string(), "cvc5": second,
                   "python": platform.python_version()},
        "instruction_starts_N": len(ctx.graph.nodes),
        "seconds": timings,
        "trusted_base": [
            "Z3 and cvc5 (no independently checkable proof certificates are "
            "produced for these bit-vector/array queries; agreement of two "
            "solvers is the cross-check)",
            "the CPU and memory model, validated on a finite sample",
            "the Python code that builds each query from the image",
            "the control-flow graph construction (analysis/cfg.py), for "
            "every result that lists J-LOCATION",
        ],
    }
    return ledger, header


def render(ledger: Ledger, header: dict) -> str:
    lines = ["# Formal status", "",
             f"Image SHA-1 `{header['rom_sha1']}`; Z3 {header['solver']['z3']}"
             f", cvc5 {header['solver']['cvc5']}.", "",
             "Generated by `python3 -m formal.run`. Every row is a statement "
             "about the machine model in `formal/model`.", "",
             "| status | count |", "|---|---|"]
    counts = ledger.counts()
    lines += [f"| `{s}` | {counts[s]} |" for s in STATUSES if s in counts]
    lines += ["", "| id | status | statement |", "|---|---|---|"]
    for item in ledger.items.values():
        lines.append(f"| {item.id} | `{item.status}` | {item.statement} |")
    return "\n".join(lines) + "\n"


def main() -> int:
    from .verify import obligations
    obligations.SAVE_QUERIES = True
    ledger, header = build()
    os.makedirs(os.path.dirname(MANIFEST), exist_ok=True)
    with open(MANIFEST, "w") as handle:
        json.dump({**header, **ledger.to_json()}, handle, indent=2,
                  sort_keys=True)
    with open(REPORT, "w") as handle:
        handle.write(render(ledger, header))
    print(json.dumps(ledger.counts(), indent=2))
    for key in ("P1", "P1-JOINT", "JOINT-CERTIFICATE", "P6-071F-PP",
                "LOC-DIRECT", "LOC-RETURN", "GRAPH-EDGES", "SEP-SEPARATION",
                "BOUNDED-P1-RESET", "BOUNDED-P1-NMI"):
        if key in ledger.items:
            print(f"{key}: {ledger.items[key].status}")
    print(f"wrote {MANIFEST}\nwrote {REPORT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
